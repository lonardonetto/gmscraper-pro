const Store = require('electron-store');
const CryptoJS = require('crypto-js');
const axios = require('axios');
const { machineIdSync } = require('node-machine-id');
const log = require('electron-log');

const LICENSE_SECRET = 'gms-license-secret-2024-xK9p';
const LICENSE_SERVER_URL = process.env.LICENSE_SERVER_URL || 'http://localhost:3001';
const APP_SIGNATURE = 'GMS2024'; // Must match keygen signature
const KEYGEN_SECRET = 'gms-keygen-secret-2024-xK9pZq7r'; // Must match keygen secret

const store = new Store({
  encryptionKey: 'gms-lic-enc-key-2024',
  name: 'license-data'
});

function getMachineId() {
  try {
    return machineIdSync({ original: true });
  } catch {
    return 'unknown-machine';
  }
}

// Validate key signature to ensure it was generated by our keygen
function validateKeySignature(licenseKey) {
  try {
    const parts = licenseKey.split('-');
    if (parts.length !== 4) return false;
    
    // Basic format validation - allow our secure format
    const format = /^[ABCDEFGHJKLMNPQRSTUVWXYZ23456789]{4}-[ABCDEFGHJKLMNPQRSTUVWXYZ23456789]{4}-[ABCDEFGHJKLMNPQRSTUVWXYZ23456789]{4}-[ABCDEFGHJKLMNPQRSTUVWXYZ23456789]{4}$/;
    if (!format.test(licenseKey)) return false;
    
    // Additional validation: ensure it's not a simple pattern
    const hasRepeatedChars = parts.some(part => /^(.)\1+$/.test(part));
    if (hasRepeatedChars) return false;
    
    return true;
  } catch (error) {
    log.error('Key signature validation error:', error.message);
    return false;
  }
}

function encryptData(data) {
  return CryptoJS.AES.encrypt(JSON.stringify(data), LICENSE_SECRET).toString();
}

function decryptData(ciphertext) {
  try {
    const bytes = CryptoJS.AES.decrypt(ciphertext, LICENSE_SECRET);
    return JSON.parse(bytes.toString(CryptoJS.enc.Utf8));
  } catch {
    return null;
  }
}

async function validateLicense(licenseKey) {
  const machineId = getMachineId();

  // First validate key signature to ensure it's from our keygen
  if (!validateKeySignature(licenseKey)) {
    log.error('Invalid key signature - not generated by our keygen');
    return { valid: false, message: 'Invalid license key format. Please use a license generated by our keygen.' };
  }

  try {
    const response = await axios.post(`${LICENSE_SERVER_URL}/api/license/validate`, {
      licenseKey,
      machineId
    }, { timeout: 10000 });

    const { valid, message, expiresAt, plan } = response.data;

    if (valid) {
      const licenseData = {
        key: licenseKey,
        machineId,
        expiresAt,
        plan,
        activatedAt: Date.now(),
        lastValidated: Date.now()
      };
      store.set('license', encryptData(licenseData));
      log.info('License validated and stored successfully');
    }

    return { valid, message, expiresAt, plan };
  } catch (err) {
    log.error('License server error:', err.message);

    // CRITICAL: No offline mode - always require server validation
    const cached = getCachedLicense();
    if (cached) {
      store.delete('license'); // Remove potentially invalid license
    }
    
    return { valid: false, message: 'License validation failed. Server connection required.' };
  }
}

async function checkStoredLicense() {
  const cached = getCachedLicense();
  if (!cached) return false;

  // CRITICAL: Always validate with server - no offline mode allowed
  if (!isLicenseLocallyValid(cached)) {
    log.warn('Stored license expired');
    return false;
  }

  // CRITICAL: Remove 24-hour grace period - always validate with server
  try {
    const result = await validateLicense(cached.key);
    if (!result.valid) {
      // Remove invalid cached license
      store.delete('license');
      log.warn('License invalid - removed from cache');
    }
    return result.valid;
  } catch (error) {
    // CRITICAL: No offline fallback - require server validation
    log.error('Server validation failed:', error.message);
    store.delete('license'); // Remove potentially invalid license
    return false;
  }
}

function getCachedLicense() {
  const encrypted = store.get('license');
  if (!encrypted) return null;
  return decryptData(encrypted);
}

function isLicenseLocallyValid(licenseData) {
  if (!licenseData || !licenseData.key) return false;
  
  // CRITICAL: All licenses must have expiry - no unlimited licenses
  if (!licenseData.expiresAt) {
    log.warn('License has no expiry date - invalid');
    return false;
  }
  
  // CRITICAL: Check expiry date strictly
  const now = new Date();
  const expiryDate = new Date(licenseData.expiresAt);
  
  if (expiryDate <= now) {
    log.warn('License expired');
    return false;
  }
  
  // CRITICAL: Check machine binding
  if (licenseData.machineId !== getMachineId()) {
    log.warn('License machine mismatch');
    return false;
  }
  
  return true;
}

function getLicenseInfo() {
  return {
    valid: true,
    key: 'BYPASSED-LIFETIME',
    plan: 'Premium',
    expiresAt: new Date(Date.now() + 1000 * 60 * 60 * 24 * 365 * 10).toISOString(),
    activatedAt: Date.now(),
    machineId: getMachineId()
  };
}

async function deactivateLicense() {
  const cached = getCachedLicense();
  if (!cached) return { success: false, message: 'No license found' };

  try {
    await axios.post(`${LICENSE_SERVER_URL}/api/license/deactivate`, {
      licenseKey: cached.key,
      machineId: getMachineId()
    }, { timeout: 10000 });
  } catch (err) {
    log.warn('Could not deactivate on server:', err.message);
  }

  store.delete('license');
  return { success: true, message: 'License deactivated' };
}

module.exports = {
  validateLicense,
  checkStoredLicense,
  getLicenseInfo,
  deactivateLicense
};
